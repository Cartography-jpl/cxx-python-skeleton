#!/usr/bin/env python
"""Make the docstring table for the nanobind bindings from doxygen XML.

    doxy2nanobind.py <doxygen xml directory> <output .cc>

Writes cxx_python_rules_nb::docstring_table() (declared in cxx_python_rules_nb.h), a map
from the qualified C++ name ("Ns::Class" or "Ns::Class::member") to its
documentation as plain text; overloads of a member are put together, each
under its signature. The binding code looks names up with
cxx_python_rules_nb::doc(name). This replaces doxy2swig.py, which wrote SWIG
%feature("docstring") directives.

Symbols in anonymous namespaces are left out (doxy2swig wrote an
unparsable line for them). If the directory doesn't exist (no doxygen),
the table is empty.
"""

import re
import sys
import textwrap
import xml.etree.ElementTree as ET
from pathlib import Path


def text_of(node) -> str:
    """Plain text of a doxygen description node, with paragraphs and lists."""
    if node is None:
        return ""
    out: list[str] = []

    def walk(n, prefix=""):
        tag = n.tag
        if tag == "para":
            buf = [n.text or ""]
            for c in n:
                if c.tag in ("itemizedlist", "orderedlist"):
                    out.append("".join(buf).strip())
                    buf = []
                    for i, li in enumerate(c.findall("listitem")):
                        mark = "* " if c.tag == "itemizedlist" else f"{i + 1}. "
                        t = " ".join(text_of(p) for p in li)
                        out.append(mark + t.strip())
                elif c.tag == "parameterlist":
                    out.append("".join(buf).strip())
                    buf = []
                    for item in c.findall("parameteritem"):
                        names = ", ".join(
                            "".join(x.itertext()) for x in item.iter("parametername")
                        )
                        desc = text_of(item.find("parameterdescription"))
                        out.append(f"{names}: {desc}")
                elif c.tag == "simplesect":
                    out.append("".join(buf).strip())
                    buf = []
                    kind = c.get("kind", "")
                    t = " ".join(text_of(p) for p in c)
                    out.append(
                        f"{kind.capitalize()}: {t}"
                        if kind not in ("see",)
                        else f"See: {t}"
                    )
                elif c.tag in ("programlisting", "verbatim"):
                    out.append("".join(buf).strip())
                    buf = []
                    out.append(
                        "\n".join(
                            "    " + "".join(l.itertext()) for l in c.iter("codeline")
                        )
                        or "".join(c.itertext())
                    )
                else:
                    buf.append("".join(c.itertext()))
                buf.append(c.tail or "")
            t = re.sub(r"[ \t\n]+", " ", "".join(buf)).strip()
            if t:
                out.append(t)
        else:
            for c in n:
                walk(c)

    walk(node)
    paras = [p for p in out if p.strip()]
    return "\n\n".join(paras)


def describe(node) -> str:
    parts = [
        text_of(node.find("briefdescription")),
        text_of(node.find("detaileddescription")),
    ]
    return "\n\n".join(p for p in parts if p)


def main() -> int:
    xmldir, outfile = Path(sys.argv[1]), Path(sys.argv[2])
    table: dict[str, list[str]] = {}
    if xmldir.is_dir():
        for f in sorted(xmldir.glob("*.xml")):
            if f.name == "index.xml":
                continue
            root = ET.parse(f).getroot()
            for cd in root.iter("compounddef"):
                kind = cd.get("kind")
                if kind not in ("class", "struct", "namespace"):
                    continue
                cname = cd.findtext("compoundname") or ""
                if "anonymous_namespace" in cname or "@" in cname:
                    continue
                if kind != "namespace":
                    d = describe(cd)
                    if d:
                        table.setdefault(cname, []).append(d)
                for md in cd.iter("memberdef"):
                    if md.get("kind") not in ("function", "variable"):
                        continue
                    name = md.findtext("name") or ""
                    d = describe(md)
                    if not d:
                        continue
                    sig = name + (md.findtext("argsstring") or "")
                    table.setdefault(f"{cname}::{name}", []).append(f"{sig}\n{d}")
    lines = [
        "// Generated by cxx_python_rules/nanobind/doxy2nanobind.py, do not edit.",
        "#include <functional>",
        "#include <map>",
        "#include <string>",
        "namespace cxx_python_rules_nb {",
        "std::map<std::string, const char*, std::less<>>& docstring_table()",
        "{",
        "  static std::map<std::string, const char*, std::less<>> t = {",
    ]
    for k in sorted(table):
        v = table[k]
        if len(v) == 1 and "::" in k and k.count("::") > 1:
            # One function: drop the signature line nanobind shows anyway.
            body = v[0].split("\n", 1)[1] if "\n" in v[0] else v[0]
        else:
            body = "\n\n".join(v)
        body = textwrap.dedent(body).replace(')doc"', ') doc"')
        lines.append(f'    {{"{k}", R"doc({body})doc"}},')
    lines += ["  };", "  return t;", "}", "}"]
    outfile.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
